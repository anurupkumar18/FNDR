    #[test]
    fn titles_are_paths_in_the_repo() {
        let dir = tempfile::tempdir().unwrap();
        let repo = dir.path().join("billing");
        std::fs::create_dir_all(repo.join("payments")).unwrap();
        std::fs::write(repo.join("Cargo.toml"), "").unwrap();
        let file = repo.join("payments").join("retry.rs");
        std::fs::write(&file, "fn retry() {}\n").unwrap();
        let (found, title) = place(&file);
        assert_eq!(found.as_deref(), Some(repo.to_str().unwrap()));
        assert_eq!(title, "billing/payments/retry.rs");
        let code = read(&file).unwrap();
        assert_eq!((code.lines, code.pieces.len()), (1, 1));
    }
